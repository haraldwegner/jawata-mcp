#!/usr/bin/env bash
# jawata-gate: lombok
# THE DISTRIBUTION SHIPS lombok.jar, AND WITH IT AS AN AGENT THE ENGINE SEES LOMBOK'S MEMBERS.
#
# WHY. jawata-studio starts a resident with -javaagent:<lombok.jar> when a workspace uses Lombok
# (studio src-tauri/src/lombok.rs), and it looks for that jar next to jawata.jar. The Tycho product
# shipped one; the Maven-built distribution of Sprint 22d does not, and the studio then degrades to
# "no agent" without a word. Found by the S19 dogfood, 2026-10-21: the java-design-patterns workspace
# compiled with 3,445 errors, every one a Lombok-generated member (LOGGER from @Slf4j, getters,
# constructors), while health_check called all 194 projects healthy. A private resident on the same
# project: 12 errors without the agent, 0 with it.
#
# What it checks, through the front door (tools/call over HTTP), against a fixture it writes itself:
#   1. dist/lombok.jar exists.
#   2. CONTROL: a resident WITHOUT the agent reports compile errors on the fixture's Lombok members.
#      (If it reports none, the fixture proves nothing, and the gate says so rather than passing.)
#   3. VARIABLE: the same resident WITH -javaagent:dist/lombok.jar reports zero.
#
# Usage: build/lombok-agent-probe.sh [dist-dir]
# Exit:  0 = all three held · 1 = a claim failed · 2 = could not run (never a pass)
set -uo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DIST="${1:-$ROOT/build/dist/target/dist}"
JAR="$DIST/jawata.jar"
LOMBOK="$DIST/lombok.jar"
LOMBOK_VERSION="${LOMBOK_VERSION:-1.18.36}"
WS="$(mktemp -d)"
PIDS=()
cleanup() {
    for p in "${PIDS[@]:-}"; do [ -n "$p" ] && kill "$p" 2>/dev/null; done
    wait 2>/dev/null
    [ -n "${PROBE_KEEP:-}" ] && echo "kept: $WS" >&2 || rm -rf "$WS"
}
trap cleanup EXIT INT TERM HUP

[ -f "$JAR" ] || { echo "COULD NOT RUN: no engine at $JAR — build first."; exit 2; }
if [ ! -f "$LOMBOK" ]; then
    echo "FAILED: the distribution ships no lombok.jar ($LOMBOK)."
    echo "jawata-studio then starts residents without the Lombok agent, silently, and every"
    echo "Lombok-generated member (LOGGER, getters, constructors) is reported as a compile error."
    exit 1
fi

# The fixture: one Maven project whose only content is a @Getter and an @Slf4j use.
P="$WS/project"
mkdir -p "$P/src/main/java/com/probe"
cat > "$P/pom.xml" <<POM
<project xmlns="http://maven.apache.org/POM/4.0.0">
  <modelVersion>4.0.0</modelVersion>
  <groupId>com.probe</groupId>
  <artifactId>lombok-fixture</artifactId>
  <version>1.0</version>
  <properties>
    <maven.compiler.source>21</maven.compiler.source>
    <maven.compiler.target>21</maven.compiler.target>
  </properties>
  <dependencies>
    <dependency>
      <groupId>org.projectlombok</groupId>
      <artifactId>lombok</artifactId>
      <version>$LOMBOK_VERSION</version>
      <scope>provided</scope>
    </dependency>
  </dependencies>
</project>
POM
cat > "$P/src/main/java/com/probe/Box.java" <<'JAVA'
package com.probe;

/** Probe fixture: every member below the field is generated by Lombok. */
@lombok.Getter
public class Box {
    private final int size = 3;

    public int twice() {
        return getSize() * 2;
    }
}
JAVA

VECTOR=""
java --add-modules jdk.incubator.vector -version >/dev/null 2>&1 && VECTOR="--add-modules jdk.incubator.vector"
start() { # name port agent
    mkdir -p "$WS/$1/data" "$WS/$1/store"
    printf '{ "name": "%s", "projects": ["%s"] }\n' "$1" "$P" > "$WS/$1/data/workspace.json"
    # shellcheck disable=SC2086
    java $VECTOR $3 -Djawata.experience.shared.dir="$WS/$1/store" -jar "$JAR" \
        -data "$WS/$1/data" -port "$2" -token "probe-$1" > "$WS/$1.log" 2>&1 &
    PIDS+=($!)
}
PORT_C="${PROBE_PORT_C:-8941}"
PORT_A="${PROBE_PORT_A:-8942}"
start control "$PORT_C" ""
start agent "$PORT_A" "-javaagent:$LOMBOK"

WS_DIR="$WS" PORT_C="$PORT_C" PORT_A="$PORT_A" python3 - <<'PY'
import json, os, sys, time, urllib.request
def call(port, name, tool, args, timeout=300):
    req = {"jsonrpc": "2.0", "id": 1, "method": "tools/call", "params": {"name": tool, "arguments": args}}
    r = urllib.request.Request("http://127.0.0.1:%s/mcp" % port, data=json.dumps(req).encode(),
        headers={"Authorization": "Bearer probe-" + name, "Mcp-Session-Id": "lombok-probe", "Content-Type": "application/json"})
    return json.loads(json.loads(urllib.request.urlopen(r, timeout=timeout).read().decode())["result"]["content"][0]["text"])
def errors(name, port):
    for _ in range(180):
        try:
            h = call(port, name, "health_check", {}, 30)
            if (h.get("data") or {}).get("project", {}).get("loaded"):
                d = call(port, name, "compile_workspace", {"limit": 5}).get("data") or {}
                return d.get("errorCount"), sorted({x.get("message") for x in d.get("diagnostics", [])})
        except Exception:
            pass
        time.sleep(1)
    return None, []
c, cm = errors("control", os.environ["PORT_C"])
a, am = errors("agent", os.environ["PORT_A"])
print(f"control (no agent): errors={c} {cm}")
print(f"agent (-javaagent:lombok.jar): errors={a} {am}")
if c is None or a is None:
    print(f"COULD NOT RUN: a resident never reported its project loaded (logs in {os.environ['WS_DIR']})"); sys.exit(2)
if c == 0:
    print("COULD NOT RUN: the control saw no error, so this fixture cannot show what the agent adds."); sys.exit(2)
if a != 0:
    print("FAILED: with the agent the engine still does not see Lombok's members."); sys.exit(1)
print("lombok gate: the distribution ships lombok.jar, and as an agent it makes Lombok's members visible.")
PY
